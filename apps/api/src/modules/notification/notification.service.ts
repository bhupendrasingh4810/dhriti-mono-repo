import { BadRequestException, Injectable } from "@nestjs/common";
import type { Notification, NotificationPreference } from "@prisma/client";

import { PrismaService } from "../../database/prisma.service";
import { EmailService } from "./email.service";
import type { CreateNotificationDto, ListNotificationsQueryDto, UpsertPreferenceDto } from "./dto/notification.dto";

export interface NotificationPage {
  notifications: Notification[];
  nextCursor: string | null;
  unreadCount: number;
  unseenCount: number;
}

export interface NotificationDeliveryOptions {
  /** Email delivery without a saved preference. Defaults off for missed calls, on for other events. */
  emailByDefault?: boolean;
  /** Skip email regardless of preference, e.g. during the recipient's quiet hours. */
  suppressEmail?: boolean;
}

@Injectable()
export class NotificationService {
  constructor(
    private readonly prisma: PrismaService,
    private readonly email: EmailService,
  ) {}

  // ---------------- In-app notifications ----------------

  async create(
    organizationId: string,
    dto: CreateNotificationDto,
    options: NotificationDeliveryOptions = {},
  ): Promise<{ eventId: string }> {
    if (dto.linkUrl) {
      throw new BadRequestException("Notification destinations must be generated by an app event");
    }
    const event = await this.prisma.notificationOutbox.create({
      data: {
        organizationId,
        recipientId: dto.userId,
        type: dto.type,
        sourceType: ["CALL", "MENTION", "DIRECT_MESSAGE", "MESSAGE"].includes(dto.type) ? "connect" : "system",
        payload: {
          version: 1,
          title: dto.title,
          body: dto.body ?? "",
          path: ["CALL", "MENTION", "DIRECT_MESSAGE", "MESSAGE"].includes(dto.type) ? "connect" : "home",
          ...options,
        },
      },
    });
    return { eventId: event.id };
  }

  async list(organizationId: string, userId: string, query: ListNotificationsQueryDto): Promise<NotificationPage> {
    const limit = Math.min(query.limit ?? 50, 200);
    const cursor = query.cursor
      ? await this.prisma.notification.findFirst({
          where: { id: query.cursor, organizationId, userId },
          select: { id: true },
        })
      : null;
    if (query.cursor && !cursor) {
      throw new BadRequestException("Notification cursor is not available in this inbox");
    }
    const notifications = await this.prisma.notification.findMany({
      where: {
        organizationId,
        userId,
        ...(query.unreadOnly ? { isRead: false } : {}),
      },
      orderBy: [{ createdAt: "desc" }, { id: "desc" }],
      take: limit + 1,
      ...(cursor ? { cursor: { id: cursor.id }, skip: 1 } : {}),
    });

    const hasMore = notifications.length > limit;
    const page = hasMore ? notifications.slice(0, limit) : notifications;

    const unreadCount = await this.prisma.notification.count({
      where: { organizationId, userId, isRead: false },
    });

    return {
      notifications: page,
      nextCursor: hasMore ? (page[page.length - 1]?.id ?? null) : null,
      unreadCount,
      unseenCount: await this.prisma.notification.count({ where: { organizationId, userId, isSeen: false } }),
    };
  }

  async markRead(organizationId: string, userId: string, notificationId: string): Promise<void> {
    await this.prisma.notification.updateMany({
      where: { id: notificationId, organizationId, userId, isRead: false },
      data: { isRead: true, isSeen: true, readAt: new Date() },
    });
  }

  async markAllRead(organizationId: string, userId: string): Promise<number> {
    const result = await this.prisma.notification.updateMany({
      where: { organizationId, userId, isRead: false },
      data: { isRead: true, isSeen: true, readAt: new Date() },
    });
    return result.count;
  }

  async unreadCount(organizationId: string, userId: string): Promise<number> {
    return this.prisma.notification.count({
      where: { organizationId, userId, isRead: false },
    });
  }

  async markSeen(organizationId: string, userId: string, ids: string[]): Promise<void> {
    await this.prisma.notification.updateMany({
      where: { organizationId, userId, isSeen: false, id: { in: ids } },
      data: { isSeen: true },
    });
  }

  // ---------------- Preferences ----------------

  async listPreferences(organizationId: string, userId: string): Promise<NotificationPreference[]> {
    return this.prisma.notificationPreference.findMany({
      where: { organizationId, userId },
      orderBy: { type: "asc" },
    });
  }

  async upsertPreference(
    organizationId: string,
    userId: string,
    dto: UpsertPreferenceDto,
  ): Promise<NotificationPreference> {
    return this.prisma.notificationPreference.upsert({
      where: {
        userId_organizationId_type: { userId, organizationId, type: dto.type },
      },
      create: {
        organizationId,
        userId,
        type: dto.type,
        inApp: dto.inApp ?? true,
        email: dto.email ?? dto.type !== "CALL",
        push: dto.push ?? false,
      },
      update: {
        ...(dto.inApp !== undefined ? { inApp: dto.inApp } : {}),
        ...(dto.email !== undefined ? { email: dto.email } : {}),
        ...(dto.push !== undefined ? { push: dto.push } : {}),
      },
    });
  }
}
