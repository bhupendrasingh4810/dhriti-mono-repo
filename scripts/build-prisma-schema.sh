#!/usr/bin/env bash
# scripts/build-prisma-schema.sh
#
# Combines prisma/parts/*.prisma into a single prisma/schema.prisma.
# All paths resolve from the repository root so the script works regardless of
# the directory it is invoked from (e.g. via a pnpm script in apps/api).

set -euo pipefail

REPO_ROOT="$(cd "$(dirname "${BASH_SOURCE[0]}")/.." && pwd)"
PRISMA_DIR="$REPO_ROOT/prisma"
PARTS_DIR="$PRISMA_DIR/parts"
OUT="$PRISMA_DIR/schema.prisma"

if [ ! -d "$PARTS_DIR" ]; then
  echo "❌ Prisma parts directory not found: $PARTS_DIR" >&2
  exit 1
fi

{
  cat << 'EOF'
// prisma/schema.prisma
// This file is generated by scripts/build-prisma-schema.sh. Do not edit directly.
// Edit the files in prisma/parts/ instead.

generator client {
  provider = "prisma-client-js"
}

datasource db {
  provider = "postgresql"
  url      = env("DATABASE_URL")
}

EOF

  # Append all parts in a stable, readable order.
  for part in address blog connect content enums hrms nexus notes notification organization platform webhook work-os; do
    file="$PARTS_DIR/$part.prisma"
    if [ ! -f "$file" ]; then
      echo "❌ Missing schema part: $file" >&2
      exit 1
    fi
    cat "$file"
    printf '\n\n'
  done
} > "$OUT"

echo "✅ Prisma schema built successfully: $OUT"